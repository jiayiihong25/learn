"""Import course data from a local scottie checkout into the tutor's courses/ folders.

scottie (github.com/jiayiihong25/scottie) is what builds the Daybook: it pulls
the "JiaYi Courses" Google Drive folder and extracts every PDF/slide deck/notes
file into text. This script reuses that work so the tutor teaches from the same
material the Daybook shows:

    courses/<course>/syllabus.md   exam dates + weekly schedule, inside a
                                   generated block; anything you write outside
                                   the block is kept
    courses/<course>/drive/*.md    one file per Drive source file, as text,
                                   with a heading per page/slide range

Only courses with files in Drive get a folder. It never touches review.md,
flashcards.csv, notes/, readings/ or past-exams/. For the full two-way sync
with the Daybook (relearn flags in, review status out), use sync_daybook.py,
which runs this too.

Usage, from the learning project root (the folder that contains .pi/):

    # once per sync, in the scottie checkout (no model calls, no pacing change):
    #   python -m drive_sync pull && python -m ingest
    python .pi/tools/import_scottie.py --scottie ../scottie

Run it with scottie's Python environment (it needs PyYAML).
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from collections import defaultdict
from datetime import date
from pathlib import Path

import yaml

START = "<!-- scottie:start (generated by .pi/tools/import_scottie.py; edits inside are overwritten) -->"
END = "<!-- scottie:end -->"
TEMPLATE = Path(__file__).resolve().parent.parent / "templates" / "course"


def safe_name(name: str) -> str:
    return re.sub(r"[^\w.\-]+", "-", name).strip("-") or "unnamed"


def load_exams(courses_yaml: Path) -> dict[str, list[tuple[str, str]]]:
    exams: dict[str, list[tuple[str, str]]] = defaultdict(list)
    data = yaml.safe_load(courses_yaml.read_text(encoding="utf-8")) or {}
    for course in data.get("courses") or []:
        for key, label in (("midterm_date", "Midterm"), ("final_date", "Final")):
            if course.get(key) is not None:
                exams[course["name"]].append((label, str(course[key])))
    return exams


def load_schedule(schedule_yaml: Path) -> dict[str, list[dict]]:
    if not schedule_yaml.exists():
        return {}
    data = yaml.safe_load(schedule_yaml.read_text(encoding="utf-8")) or {}
    return data.get("courses") or {}


def load_chunks(index_path: Path) -> list[dict]:
    data = json.loads(index_path.read_text(encoding="utf-8"))
    if data.get("schema_version") != 1:
        sys.exit(f"{index_path}: unexpected schema_version {data.get('schema_version')!r}")
    return data["chunks"]


def cell(text) -> str:
    return str(text or "").replace("|", "\\|").replace("\n", " ").strip()


def generated_block(course: str, exams, weeks, drive_files: dict[str, str]) -> str:
    lines = [START, "", f"_Imported from scottie / the Daybook on {date.today().isoformat()}._", ""]
    lines += ["## Exams (from courses.yaml)", ""]
    if exams:
        lines += ["| Assessment | Date |", "|---|---|"]
        lines += [f"| {name} | {when} |" for name, when in sorted(exams, key=lambda e: e[1])]
    else:
        lines.append("No exam dates in courses.yaml.")
    lines += ["", "## Weekly schedule (from schedule.yaml)", ""]
    if weeks:
        lines += ["| Week | Starts | Topic | Items |", "|---|---|---|---|"]
        for w in weeks:
            items = []
            for item in w.get("items") or []:
                files = [
                    f"`drive/{drive_files[f]}`" if f in drive_files else f"{f} (not in Drive)"
                    for f in item.get("files") or []
                ]
                items.append(cell(item.get("title")) + (f" → {', '.join(files)}" if files else ""))
            topic = cell(w.get("topic"))
            if w.get("summary"):
                topic += f" — {cell(w['summary'])}"
            week = w.get("week")
            label = cell(w.get("label") or (f"Week {week}" if isinstance(week, int) else week))
            lines.append(f"| {label} | {w.get('starts', '')} | {topic} | {'<br>'.join(items)} |")
    else:
        lines.append("No schedule for this course in schedule.yaml.")
    lines += ["", "## Material from Drive", ""]
    lines += [f"- `drive/{md}` ← {src}" for src, md in sorted(drive_files.items())] or ["None."]
    lines += ["", END]
    return "\n".join(lines)


def write_syllabus(path: Path, course: str, block: str) -> None:
    if path.exists():
        text = path.read_text(encoding="utf-8")
        if START in text and END in text:
            head, rest = text.split(START, 1)
            text = head + block + rest.split(END, 1)[1]
        else:
            title, _, body = text.partition("\n")
            text = f"{title}\n\n{block}\n{body}"
    else:
        text = (
            f"# {course}\n\n{block}\n\n"
            "## Exam formats and grading (fill in by hand)\n\n"
            "Format of each exam (e.g. 40 MC + 3 short answer, closed book), weights, and how the "
            "instructor grades (\"wants course terminology\", \"definitions word-for-word\", "
            "\"always a case question\"):\n\n-\n\n"
            "## Flagged as important\n\n-\n"
        )
    path.write_text(text, encoding="utf-8")


def write_drive_notes(drive_dir: Path, chunks: list[dict]) -> dict[str, str]:
    """One markdown file per source file. Returns {source file name: md file name}."""
    if drive_dir.exists():
        shutil.rmtree(drive_dir)  # fully generated; a file removed from Drive disappears here too
    drive_dir.mkdir(parents=True)
    by_file: dict[str, list[dict]] = defaultdict(list)
    for c in chunks:
        by_file[Path(c["source_file"]).name].append(c)
    names: dict[str, str] = {}
    for src, file_chunks in sorted(by_file.items()):
        md = safe_name(Path(src).stem) + ".md"
        file_chunks.sort(key=lambda c: (c["unit_start"], c["unit_end"]))
        topic = file_chunks[0]["topic"]
        parts = [f"# {src}", "", f"Topic: {topic}. Text extracted from Drive by scottie; cite as `{src}, <range>`.", ""]
        for c in file_chunks:
            parts += [f"## {c['unit_range']}", "", c["text"].strip(), ""]
        (drive_dir / md).write_text("\n".join(parts), encoding="utf-8")
        names[src] = md
    return names


def import_courses(scottie: Path, out: Path) -> dict[str, Path]:
    """Writes a folder per course that has material in Drive. Returns {course: folder}.

    Courses listed in courses.yaml or schedule.yaml but with no files in Drive
    are skipped: there's nothing to teach from yet.
    """
    data = scottie / "data"
    index_path = data / "content_index.json"
    for needed in (data / "courses.yaml", index_path):
        if not needed.exists():
            sys.exit(f"Missing {needed}. In {scottie}, run: python -m drive_sync pull && python -m ingest")

    exams = load_exams(data / "courses.yaml")
    schedule = load_schedule(data / "schedule.yaml")
    by_course: dict[str, list[dict]] = defaultdict(list)
    for c in load_chunks(index_path):
        by_course[c["course"]].append(c)

    for course in sorted((set(exams) | set(schedule)) - set(by_course)):
        print(f"- {course}: skipped, no course files in Drive yet")

    folders: dict[str, Path] = {}
    for course in sorted(by_course):
        folder = out / safe_name(course)
        new = not folder.exists()
        folder.mkdir(parents=True, exist_ok=True)
        for sub in ("notes", "readings", "past-exams"):
            (folder / sub).mkdir(exist_ok=True)
        for keep in ("review.md", "flashcards.csv"):
            if not (folder / keep).exists():
                shutil.copy(TEMPLATE / keep, folder / keep)
        drive_files = write_drive_notes(folder / "drive", by_course[course])
        write_syllabus(folder / "syllabus.md", course, generated_block(course, exams.get(course, []), schedule.get(course, []), drive_files))
        print(f"{'+' if new else '~'} {folder}: {len(drive_files)} Drive files, "
              f"{len(exams.get(course, []))} exams, {len(schedule.get(course, []))} schedule weeks")
        folders[course] = folder
    return folders


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--scottie", type=Path, default=Path("../scottie"), help="path to the scottie checkout")
    parser.add_argument("--out", type=Path, default=Path("courses"), help="the tutor's courses folder")
    args = parser.parse_args()
    import_courses(args.scottie, args.out)


if __name__ == "__main__":
    main()
